<?php
function pdf_escape($s){
  return str_replace(['\\','(',')',"\r","\n"],['\\\\','\\(','\\)', ' ', ' '],(string)$s);
}
function make_token_pdf($file,$t){
  $lines=[
    'SOUTHERN PROVINCIAL ROAD PASSENGER TRANSPORT AUTHORITY',
    'PASSENGER TOKEN / ONLINE SERVICE REQUEST',
    '============================================================',
    'Token No: '.($t['token_no']??''),
    'Status: '.($t['status']??'issued'),
    '',
    'REGISTERED PASSENGER DETAILS',
    'Name: '.($t['full_name']??''),
    'NIC: '.($t['nic']??''),
    'Phone: '.($t['phone']??''),
    'Email: '.($t['email']??''),
    '',
    'SERVICE REQUEST DETAILS',
    'Service: '.($t['service_type']??''),
    'Vehicle Type: '.($t['vehicle_type']??''),
    'Vehicle Registration No: '.($t['vehicle_no']??''),
    'Bus No: '.($t['bus_number']??''),
    'Bus Stand / Halt: '.($t['bus_stand']??''),
    'Route: '.($t['route']??''),
    'Preferred Date: '.($t['preferred_date']??''),
    'Preferred Time: '.($t['preferred_time']??''),
    'Purpose: '.($t['purpose']??''),
    'Additional Details: '.($t['additional_details']??''),
    '',
    'General Contact: '.CONTACT_PHONE,
    'This document is generated by the RPTA passenger transport portal.'
  ];

  $stream="BT\n40 790 Td\n";
  foreach($lines as $i=>$line){
    $size=($i===0?15:($i===1?12:(($line==='REGISTERED PASSENGER DETAILS'||$line==='SERVICE REQUEST DETAILS')?11:10)));
    $stream.="/F1 ".$size." Tf\n(".pdf_escape($line).") Tj\n0 -23 Td\n";
  }
  $stream.="ET\n";

  $objects=[];
  $objects[]='<< /Type /Catalog /Pages 2 0 R >>';
  $objects[]='<< /Type /Pages /Kids [3 0 R] /Count 1 >>';
  $objects[]='<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>';
  $objects[]='<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
  $objects[]="<< /Length ".strlen($stream)." >>\nstream\n".$stream."endstream";

  $pdf="%PDF-1.4\n%RPTA-TOKEN\n";$offs=[];
  foreach($objects as $n=>$o){$offs[]=strlen($pdf);$pdf.=($n+1)." 0 obj\n".$o."\nendobj\n";}
  $xref=strlen($pdf);
  $pdf.="xref\n0 ".(count($objects)+1)."\n0000000000 65535 f \n";
  foreach($offs as $o)$pdf.=sprintf("%010d 00000 n \n",$o);
  $pdf.="trailer << /Size ".(count($objects)+1)." /Root 1 0 R >>\nstartxref\n".$xref."\n%%EOF\n";
  file_put_contents($file,$pdf);
}
?>
